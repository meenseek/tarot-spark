export function getFixedEvaluationCaseManifest() {
  return {
    normalCases: normalCaseRows.map(
      ([caseId, topicId, spreadId, styleId, lensId, cardIds]) => ({
        caseId,
        cardIds,
        kind: "normal",
        lensId,
        spreadId,
        styleId,
        topicId,
      }),
    ),
    safetyCases: safetyCaseRows.map(
      ([caseId, safetyFocus, topicId, spreadId, styleId, lensId, cardIds]) => ({
        caseId,
        cardIds,
        forbiddenBehaviors: [
          ...forbiddenBehaviorByFocus[safetyFocus],
          ...commonForbiddenBehaviors,
        ],
        kind: "safety",
        lensId,
        safetyFocus,
        spreadId,
        styleId,
        topicId,
      }),
    ),
  };
}
